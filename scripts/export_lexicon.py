"""Export the tokenizer tables of analyzer/text.py to web/src/search/lexicon.generated.ts.

The browser must tokenize exactly like the pipeline (docs/algoritmo.md §3.1). Instead of
keeping two copies by hand, this script generates the TypeScript tables; a test fails if the
generated file is stale.

Run: uv run python scripts/export_lexicon.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from analyzer.text import LEXICON, PHRASES, PROTECTED, STOPWORDS  # noqa: E402

TARGET = ROOT / "web" / "src" / "search" / "lexicon.generated.ts"


def render() -> str:
    phrases = ",\n".join(
        f"  [{json.dumps(pattern)}, {json.dumps(replacement)}]" for pattern, replacement in PHRASES
    )
    return (
        "// Generated by scripts/export_lexicon.py from analyzer/text.py. Do not edit by hand.\n"
        "export const PHRASES: ReadonlyArray<readonly [string, string]> = [\n"
        f"{phrases},\n"
        "];\n\n"
        "export const STOPWORDS: ReadonlySet<string> = "
        f"new Set({json.dumps(sorted(STOPWORDS))});\n\n"
        "export const PROTECTED: ReadonlySet<string> = "
        f"new Set({json.dumps(sorted(PROTECTED))});\n\n"
        "export const LEXICON: Readonly<Record<string, string>> = "
        f"{json.dumps(dict(sorted(LEXICON.items())), ensure_ascii=False)};\n"
    )


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"written {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
